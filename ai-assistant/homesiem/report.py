def _human(n: int) -> str:
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if abs(n) < 1024:
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024
    return f"{n:.1f} PB"


def _env() -> Environment:
    env = Environment(loader=FileSystemLoader(Path(__file__).parent / "templates"),
                      trim_blocks=True, lstrip_blocks=True, autoescape=False)
    env.filters["e_md"] = lambda s: str(s).replace("|", "\\|").replace("<", "&lt;")
    env.filters["dt"] = lambda d: d.strftime("%Y-%m-%d %H:%M") if d else "-"
    env.filters["tojson_pretty"] = lambda o: json.dumps(o, indent=2, default=str, ensure_ascii=False)
    env.filters["mitre_links"] = lambda ts: ", ".join(
        f"[{t}](https://attack.mitre.org/techniques/{t.replace('.', '/')}/)" for t in ts) or "-"
    return env


def build_stats(ds: Dataset, findings: list[Finding], is_home) -> dict:
    s = ds.summary()
    s["findings_total"] = len(findings)
    s["internal_hosts"] = len({c.src_ip for c in ds.conns if is_home(c.src_ip)})
    return s


def render(ds: Dataset, findings: list[Finding], summary: str, stats: dict, cfg: dict,
           ai_model: str, is_home) -> tuple[str, dict]:
    lang = cfg.get("language", "en")
    L = LABELS[lang]
    findings = sorted(findings, key=lambda f: (-(f.ai_risk or 0), -f.severity_rank, -f.count))

    times = [c.ts for c in ds.conns] + [q.ts for q in ds.dns] + [a.first_seen for a in ds.alerts if a.first_seen]
    fmt = "%Y-%m-%d %H:%M"
    period_start = min(times).strftime(fmt) if times else "-"
    period_end = max(times).strftime(fmt) if times else "-"

    talkers: dict[str, list[int]] = defaultdict(lambda: [0, 0, 0])
    for c in ds.conns:
        if is_home(c.src_ip):
            t = talkers[c.src_ip]
            t[0] += 1
            t[1] += c.orig_bytes
            t[2] += c.resp_bytes
    top_talkers = [dict(host=h, conns=v[0], out=_human(v[1]), inb=_human(v[2]))
                   for h, v in sorted(talkers.items(), key=lambda kv: -kv[1][1])[:10]]
    top_domains = Counter(parent_domain(q.query) for q in ds.dns).most_common(10)
    mitre_counts = Counter(t for f in findings for t in f.mitre).most_common()
    sev = Counter(f.severity for f in findings)

    md = _env().get_template("report.md.j2").render(
        L=L, summary=summary, findings=findings, period_start=period_start, period_end=period_end,
        generated=datetime.now(timezone.utc).strftime(fmt + " UTC"), ai_model=ai_model,
        stats_rows=[(L["stats"].get(k, k), f"{v:,}") for k, v in stats.items()],
        sev={k: sev.get(k, 0) for k in ("critical", "high", "medium", "low", "info")},
        top_talkers=top_talkers, top_domains=top_domains, mitre_counts=mitre_counts,
    )
    data = {"generated": datetime.now(timezone.utc).isoformat(), "period": [period_start, period_end],
            "stats": stats, "summary": summary, "findings": [f.to_dict() for f in findings]}
    return md, data


def write(md: str, data: dict, out_dir: str, lang: str) -> tuple[Path, Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("%Y-%m-%d")
    md_path = out / f"report-{stamp}.{lang}.md"
    json_path = out / f"findings-{stamp}.json"
    md_path.write_text(md, encoding="utf-8")
    json_path.write_text(json.dumps(data, indent=2, ensure_ascii=False, default=str), encoding="utf-8")
    return md_path, json_path
